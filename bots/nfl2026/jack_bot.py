def _pos_of(raw):
    try:
        return json.loads(raw)[0]
    except Exception:
        return "?"


def _me(conn):
    row = conn.exec_driver_sql("SELECT current_bot_id, current_draft_pick FROM game_statuses LIMIT 1").fetchone()
    return row[0], int(row[1])


def _my_positions(conn, me):
    rows = conn.exec_driver_sql(
        "SELECT id, allowed_positions FROM players WHERE current_bot_id = ? ORDER BY pick_chosen", (me,)).fetchall()
    return [(str(pid), _DATA[str(pid)][0] if str(pid) in _DATA else _pos_of(raw)) for pid, raw in rows]


def read_draft_state(conn):
    me, pick_no = _me(conn)
    n_teams = conn.exec_driver_sql("SELECT COUNT(*) FROM bots").fetchone()[0]
    available = {str(pid) for (pid,) in
                 conn.exec_driver_sql("SELECT id FROM players WHERE availability = 'AVAILABLE'").fetchall()}
    return DraftState(my_roster=_my_positions(conn, me), available=available, pick_no=pick_no, n_teams=n_teams)


def _tier_b(conn):
    """choose_pick under a deadline. A daemon thread, so a hung core can't block process exit."""
    state = read_draft_state(conn)
    box = {}

    def run():
        try:
            box["pid"] = choose_pick(state)
        except BaseException as e:  # re-raised below
            box["err"] = e

    t = threading.Thread(target=run, daemon=True)
    t.start()
    t.join(CHOOSE_DEADLINE_S)
    if t.is_alive():
        raise TimeoutError("choose_pick deadline")
    if "err" in box:
        raise box["err"]
    return box["pid"]


def _tier_a(conn):
    return static_board_pick(read_draft_state(conn))


def _sql_pick(conn, order_by):
    me, _ = _me(conn)
    capped = {pos for _, pos in _my_positions(conn, me) if pos in CAPPED}
    rows = conn.exec_driver_sql(
        f"SELECT id, allowed_positions FROM players WHERE availability = 'AVAILABLE' {order_by}").fetchall()
    for pid, raw in rows:
        if _pos_of(raw) not in capped:
            return str(pid)
    return str(rows[0][0]) if rows else None


def _tier_c(conn):
    return _sql_pick(conn, "ORDER BY rank")


def _tier_d(conn):
    return _sql_pick(conn, "")


TIERS = (("B", _tier_b), ("A", _tier_a), ("C", _tier_c), ("D", _tier_d))


def _is_available(conn, pid):
    row = conn.exec_driver_sql("SELECT availability FROM players WHERE id = ?", (pid,)).fetchone()
    return row is not None and row[0] == "AVAILABLE"


def pick_with_fallbacks(conn, tiers=None):
    for name, fn in (TIERS if tiers is None else tiers):
        try:
            pid = fn(conn)
            if pid is not None and _is_available(conn, str(pid)):
                return name, str(pid)
        except Exception:
            continue
    raise RuntimeError("no available player")


def draft_player() -> str:
    db = DatabaseManager()
    try:
        with db.engine.connect() as conn:
            tier, pid = pick_with_fallbacks(conn)
        score = _DATA[pid][2] if pid in _DATA else 0.0
        print(f"jack_bot pick={pid} score={score:.2f} tier={tier}")
        return pid
    finally:
        db.close()


