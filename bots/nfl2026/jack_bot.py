@dataclass
class DraftState:
    my_roster: list  # [(id, pos)] in pick order
    available: set
    pick_no: int  # 1-based overall pick
    n_teams: int

    @property
    def my_slot(self):
        return slot_for_pick(self.pick_no, self.n_teams)


def slot_for_pick(pick_no, n_teams):
    rnd, idx = divmod(pick_no - 1, n_teams)
    return idx + 1 if rnd % 2 == 0 else n_teams - idx


def _item_positions(item):
    return FLEX_POS if item in ("FLEX", "TRIO") else (item,)


def build_queue(roster_positions, slot):
    queue = list(SLOT12_QUEUE if slot <= 2 else DEFAULT_QUEUE)
    for n, pos in enumerate(roster_positions):
        if n == 0 and queue and queue[0] == "TRIO" and pos in FLEX_POS:
            queue.pop(0)
            continue
        i = next((k for k, it in enumerate(queue) if it == pos), None)
        if i is None and pos in FLEX_POS:
            i = next((k for k, it in enumerate(queue) if it in ("FLEX", "TRIO")), None)
        if i is not None:
            queue.pop(i)
    return queue


def _key(data, pid):
    pos, ppg, vor, rank = data[pid][:4]
    return (-vor, -ppg, rank)


def _flex_key(data, pid):
    """FLEX slots score raw points, so positional VOR baselines would skew the pick toward RBs."""
    pos, ppg, vor, rank = data[pid][:4]
    return (-ppg, -vor, rank)


def _best(data, avail, positions, roster_positions, key=_key):
    """Best available non-zero player at the given positions, respecting the TE cap."""
    te_full = roster_positions.count("TE") >= MAX_TE
    cands = [p for p in avail
             if data[p][0] in positions and data[p][1] > 0 and not (te_full and data[p][0] == "TE")]
    return min(cands, key=lambda p: key(data, p)) if cands else None


def choose_pick(state, data=None):
    data = _DATA if data is None else data
    roster_pos = [pos for _, pos in state.my_roster]
    queue = build_queue(roster_pos, state.my_slot)
    avail = [p for p in state.available if p in data]
    no_override = not state.my_roster and state.my_slot <= 2
    if queue and queue[0] == "TRIO":
        for pid in TRIO_IDS:
            if pid in state.available:
                return pid
        queue[0] = "FLEX"
    for n, item in enumerate(queue):
        planned = _best(data, avail, _item_positions(item), roster_pos, _flex_key if item == "FLEX" else _key)
        if planned is None:
            continue
        if no_override or item in CAPPED:
            return planned
        later = {pos for it in queue[n + 1:] if it not in CAPPED for pos in _item_positions(it)}
        best_q = None
        for pos in later:
            q = _best(data, avail, (pos,), roster_pos)
            if q is not None and data[q][2] - data[planned][2] > OVERRIDE_T:
                if best_q is None or _key(data, q) < _key(data, best_q):
                    best_q = q
        return best_q or planned
    return static_board_pick(state, data)


def static_board_pick(state, data=None):
    """Fallback A: best VOR among positions still covered by a remaining queue item."""
    data = _DATA if data is None else data
    roster_pos = [pos for _, pos in state.my_roster]
    queue = build_queue(roster_pos, state.my_slot)
    allowed = {pos for it in queue for pos in _item_positions(it)}
    avail = [p for p in state.available if p in data]
    pid = _best(data, avail, allowed, roster_pos)
    if pid is None:
        raise LookupError("no eligible player on the static board")
    return pid


